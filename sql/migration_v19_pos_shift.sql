-- ---------------------------------------------------------------------------
-- sell_bill — ขายหลายชิ้นใน 1 บิล แบบ atomic
--   p_lines = [{"item_id":"…","price":120}, …]  ราคาต่อชิ้นที่ "ตกลงจริง"
--   (browser กระจายส่วนลด/ราคาเหมาลงแต่ละชิ้นมาแล้ว — ดู assets/js/money.js)
--   ถ้า p_bill_id เคยบันทึกแล้ว → คืนบิลเดิม (duplicate=true) ไม่สร้างซ้ำ
--   ถ้าชิ้นไหนขายไม่ได้ → rollback ทั้งบิล
-- ---------------------------------------------------------------------------
create or replace function public.sell_bill(
  p_bill_id uuid,
  p_lines jsonb,
  p_payment_method text,
  p_channel text default 'street_market',
  p_cash_received numeric default null,
  p_note text default null,
  p_sell_reserved boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bill bills%rowtype;
  v_shift uuid;
  v_line jsonb;
  v_item items%rowtype;
  v_price numeric;
  v_total numeric := 0;
  v_list numeric := 0;
begin
  if p_bill_id is null then raise exception 'ไม่มีเลขบิล'; end if;

  -- idempotent: ส่งซ้ำด้วย id เดิม → คืนบิลเดิม
  select * into v_bill from bills where id = p_bill_id;
  if found then
    return jsonb_build_object('bill_id', v_bill.id, 'bill_no', v_bill.bill_no, 'total', v_bill.total,
                              'list_total', v_bill.list_total, 'shift_id', v_bill.shift_id, 'duplicate', true);
  end if;

  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'ตะกร้าว่าง';
  end if;
  if p_payment_method not in ('cash','transfer','government') then raise exception 'วิธีจ่ายเงินไม่ถูกต้อง'; end if;
  if (select count(distinct l->>'item_id') from jsonb_array_elements(p_lines) l) <> jsonb_array_length(p_lines) then
    raise exception 'มีสินค้าซ้ำในบิล';
  end if;

  select id into v_shift from shifts where closed_at is null limit 1; -- ผูกกับกะที่เปิดอยู่ (ถ้ามี)

  insert into bills(id, shift_id, channel, payment_method, cash_received, note)
  values (p_bill_id, v_shift, coalesce(p_channel, 'street_market'), p_payment_method, p_cash_received, p_note)
  returning * into v_bill;

  for v_line in select * from jsonb_array_elements(p_lines) loop
    select * into v_item from items where id = (v_line->>'item_id')::uuid for update;
    if not found then raise exception 'ไม่พบสินค้าในบิล'; end if;
    if v_item.status <> 'available' then raise exception '"%" ไม่ได้อยู่ในสต็อกแล้ว', v_item.item_name; end if;
    if v_item.intake_status <> 'listed' then raise exception '"%" ยังลงไม่ครบ (รอรูป)', v_item.item_name; end if;

    v_price := round((v_line->>'price')::numeric, 2);
    if v_price is null or v_price < 0 then raise exception 'ราคาของ "%" ไม่ถูกต้อง', v_item.item_name; end if;

    if exists (select 1 from reservations where item_id = v_item.id and status = 'active') then
      if not p_sell_reserved then raise exception '"%" ถูกจองไว้แล้ว', v_item.item_name; end if;
      update reservations set status = 'sold', bill_id = p_bill_id, closed_at = now()
       where item_id = v_item.id and status = 'active';
    end if;

    insert into sales(item_id, bill_id, sale_price, list_price, cost_price, payment_method, channel, note)
    values (v_item.id, p_bill_id, v_price, v_item.current_price, v_item.cost_price, p_payment_method,
            coalesce(p_channel, 'street_market'), p_note);
    update items set status = 'sold', sold_at = now() where id = v_item.id;

    v_total := v_total + v_price;
    v_list := v_list + v_item.current_price;
  end loop;

  if p_payment_method = 'cash' and p_cash_received is not null and p_cash_received < v_total then
    raise exception 'รับเงินน้อยกว่ายอดบิล';
  end if;

  update bills set total = v_total, list_total = v_list where id = p_bill_id returning * into v_bill;
  return jsonb_build_object('bill_id', v_bill.id, 'bill_no', v_bill.bill_no, 'total', v_total,
                            'list_total', v_list, 'shift_id', v_shift, 'duplicate', false);
end;
$$;

-- ---------------------------------------------------------------------------
-- void_bill — ยกเลิกทั้งบิล (ปุ่ม "เลิกทำ" หลังขาย / กดผิด)
--   ทุกชิ้นกลับเป็นพร้อมขาย, การจองที่ขายไปในบิลนี้กลับเป็น active
-- ---------------------------------------------------------------------------
create or replace function public.void_bill(p_bill_id uuid, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bill bills%rowtype;
  v_count int;
begin
  select * into v_bill from bills where id = p_bill_id for update;
  if not found then raise exception 'ไม่พบบิล'; end if;
  if v_bill.voided_at is not null then raise exception 'บิลนี้ถูกยกเลิกไปแล้ว'; end if;

  update items i set status = 'available', sold_at = null
    from sales s
   where s.bill_id = p_bill_id and s.voided_at is null and i.id = s.item_id and i.status = 'sold';
  update sales set voided_at = now(), void_reason = coalesce(p_reason, 'ยกเลิกทั้งบิล')
   where bill_id = p_bill_id and voided_at is null;
  get diagnostics v_count = row_count;
  update reservations set status = 'active', bill_id = null, closed_at = null
   where bill_id = p_bill_id and status = 'sold';
  update bills set voided_at = now(), void_reason = p_reason where id = p_bill_id;

  return jsonb_build_object('bill_id', p_bill_id, 'voided_items', v_count);
end;
$$;

-- ---------------------------------------------------------------------------
-- void_sale (อัปเดตจาก V15) — คืน/ยกเลิกทีละชิ้น
--   เพิ่ม: ถ้าทุกชิ้นในบิลถูกยกเลิกหมด → บิลถูกยกเลิกด้วย, การจองกลับเป็น active
-- ---------------------------------------------------------------------------
create or replace function public.void_sale(p_sale_id uuid, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sale sales%rowtype;
begin
  select * into v_sale from sales where id = p_sale_id for update;
  if not found then raise exception 'ไม่พบรายการขาย'; end if;
  if v_sale.voided_at is not null then raise exception 'รายการนี้ถูกยกเลิกไปแล้ว'; end if;

  update sales set voided_at = now(), void_reason = p_reason where id = p_sale_id;
  update items set status = 'available', sold_at = null where id = v_sale.item_id and status = 'sold';

  if v_sale.bill_id is not null then
    update reservations set status = 'active', bill_id = null, closed_at = null
     where bill_id = v_sale.bill_id and item_id = v_sale.item_id and status = 'sold';
    if not exists (select 1 from sales where bill_id = v_sale.bill_id and voided_at is null) then
      update bills set voided_at = now(), void_reason = coalesce(p_reason, 'คืนครบทุกชิ้น')
       where id = v_sale.bill_id and voided_at is null;
    end if;
  end if;

  return jsonb_build_object('sale_id', p_sale_id, 'item_id', v_sale.item_id, 'bill_id', v_sale.bill_id);
end;
$$;

-- ---------------------------------------------------------------------------
-- open_shift — เปิดกะ (ใส่เงินทอนตั้งต้น)
-- ---------------------------------------------------------------------------
create or replace function public.open_shift(p_opening_cash numeric default 0, p_location text default 'ถนนคนเดิน')
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_shift shifts%rowtype;
begin
  if exists (select 1 from shifts where closed_at is null) then raise exception 'มีกะที่เปิดอยู่แล้ว ปิดกะเดิมก่อน'; end if;
  if coalesce(p_opening_cash, 0) < 0 then raise exception 'เงินทอนตั้งต้นไม่ถูกต้อง'; end if;
  insert into shifts(opening_cash, location) values (coalesce(p_opening_cash, 0), coalesce(nullif(trim(p_location), ''), 'ถนนคนเดิน'))
  returning * into v_shift;
  return to_jsonb(v_shift);
end;
$$;

-- ---------------------------------------------------------------------------
-- shift_totals — ตัวเลขของกะ (ใช้ทั้งระหว่างกะและตอนปิด)
--   เงินที่ควรมีในลิ้นชัก = เงินทอนตั้งต้น + ขายเงินสด − ค่าใช้จ่ายที่หยิบจากลิ้นชัก
--   นับเฉพาะ sales ที่ไม่ถูกยกเลิก
-- ---------------------------------------------------------------------------
create or replace function public.shift_totals(p_shift_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_shift shifts%rowtype;
  v jsonb;
  e jsonb;
begin
  select * into v_shift from shifts where id = p_shift_id;
  if not found then raise exception 'ไม่พบกะ'; end if;

  select jsonb_build_object(
    'revenue', coalesce(sum(s.sale_price), 0),
    'cogs', coalesce(sum(s.cost_price), 0),
    'list_total', coalesce(sum(coalesce(s.list_price, s.sale_price)), 0),
    'cash_sales', coalesce(sum(s.sale_price) filter (where s.payment_method = 'cash'), 0),
    'transfer_sales', coalesce(sum(s.sale_price) filter (where s.payment_method = 'transfer'), 0),
    'government_sales', coalesce(sum(s.sale_price) filter (where s.payment_method = 'government'), 0),
    'items', count(s.id),
    'bills', count(distinct s.bill_id)
  ) into v
  from sales s join bills b on b.id = s.bill_id
  where b.shift_id = p_shift_id and s.voided_at is null;

  select jsonb_build_object(
    'expenses', coalesce(sum(amount), 0),
    'expenses_drawer', coalesce(sum(amount) filter (where paid_from = 'drawer'), 0),
    'expense_lines', coalesce(jsonb_agg(jsonb_build_object('category', category, 'amount', amount, 'paid_from', paid_from) order by coalesce(expense_at, created_at)), '[]'::jsonb)
  ) into e
  from expenses where shift_id = p_shift_id;

  return v || e || jsonb_build_object(
    'shift_id', v_shift.id,
    'location', v_shift.location,
    'opened_at', v_shift.opened_at,
    'closed_at', v_shift.closed_at,
    'opening_cash', v_shift.opening_cash,
    'expected_cash', v_shift.opening_cash + (v->>'cash_sales')::numeric - (e->>'expenses_drawer')::numeric,
    'left_today', (v->>'revenue')::numeric - (e->>'expenses')::numeric,
    'real_profit', (v->>'revenue')::numeric - (v->>'cogs')::numeric - (e->>'expenses')::numeric
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- close_shift — นับเงินแล้วปิดกะ
--   ขาด/เกิน ต้องมีเหตุผลเสมอ, เก็บ snapshot ตัวเลขทั้งกะไว้ใน summary
-- ---------------------------------------------------------------------------
create or replace function public.close_shift(p_shift_id uuid, p_counted_cash numeric, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_shift shifts%rowtype;
  t jsonb;
  v_expected numeric;
  v_diff numeric;
begin
  select * into v_shift from shifts where id = p_shift_id for update;
  if not found then raise exception 'ไม่พบกะ'; end if;
  if v_shift.closed_at is not null then raise exception 'กะนี้ปิดไปแล้ว'; end if;
  if p_counted_cash is null or p_counted_cash < 0 then raise exception 'ใส่ยอดเงินที่นับได้'; end if;

  t := public.shift_totals(p_shift_id);
  v_expected := (t->>'expected_cash')::numeric;
  v_diff := round(p_counted_cash - v_expected, 2);
  if v_diff <> 0 and coalesce(trim(p_reason), '') = '' then
    raise exception 'เงินขาด/เกิน % บาท ต้องใส่เหตุผล', v_diff;
  end if;

  t := t || jsonb_build_object('counted_cash', p_counted_cash, 'cash_diff', v_diff, 'diff_reason', p_reason, 'closed_at', now());
  update shifts set closed_at = now(), expected_cash = v_expected, counted_cash = p_counted_cash,
         cash_diff = v_diff, diff_reason = nullif(trim(coalesce(p_reason, '')), ''), summary = t
   where id = p_shift_id;
  return t;
end;
$$;

-- ---------------------------------------------------------------------------
-- reserve_item / release_reservation — จองสินค้า
-- ---------------------------------------------------------------------------
create or replace function public.reserve_item(
  p_item_id uuid,
  p_customer_name text,
  p_channel text default 'instagram',
  p_deposit numeric default 0,
  p_due_date date default null,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_item items%rowtype; v_res reservations%rowtype;
begin
  select * into v_item from items where id = p_item_id for update;
  if not found then raise exception 'ไม่พบสินค้า'; end if;
  if v_item.status <> 'available' then raise exception 'สินค้านี้ไม่ได้อยู่ในสต็อก'; end if;
  if exists (select 1 from reservations where item_id = p_item_id and status = 'active') then
    raise exception 'สินค้านี้ถูกจองไว้แล้ว';
  end if;
  insert into reservations(item_id, customer_name, channel, deposit, due_date, note)
  values (p_item_id, trim(p_customer_name), coalesce(p_channel, 'instagram'), coalesce(p_deposit, 0), p_due_date, p_note)
  returning * into v_res;
  return to_jsonb(v_res);
end;
$$;

create or replace function public.release_reservation(p_reservation_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  update reservations set status = 'released', closed_at = now()
   where id = p_reservation_id and status = 'active';
  if not found then raise exception 'ไม่พบการจองที่ยังเปิดอยู่'; end if;
  return jsonb_build_object('reservation_id', p_reservation_id);
end;
$$;

-- ---------------------------------------------------------------------------
-- storage_usage — ใช้พื้นที่ไปเท่าไหร่ (แพ็กเกจฟรี: DB 500 MB, Storage 1 GB)
-- ---------------------------------------------------------------------------
create or replace function public.storage_usage()
returns jsonb
language sql
stable
security definer
set search_path = public, storage
as $$
  select jsonb_build_object(
    'db_bytes', pg_database_size(current_database()),
    'image_bytes', coalesce((select sum((metadata->>'size')::bigint) from storage.objects where bucket_id = 'item-images'), 0),
    'image_files', (select count(*) from storage.objects where bucket_id = 'item-images'),
    'items', (select count(*) from public.items),
    'sold_items', (select count(*) from public.items where status = 'sold')
  );
$$;

-- สิทธิ์เรียก RPC (ถ้าใช้ migration_v20_auth_lock.sql จะถอน anon ออกทีหลัง)
do $$
declare f text;
begin
  foreach f in array array[
    'sell_bill(uuid,jsonb,text,text,numeric,text,boolean)',
    'void_bill(uuid,text)',
    'void_sale(uuid,text)',
    'open_shift(numeric,text)',
    'shift_totals(uuid)',
    'close_shift(uuid,numeric,text)',
    'reserve_item(uuid,text,text,numeric,date,text)',
    'release_reservation(uuid)',
    'storage_usage()'
  ] loop
    execute format('revoke all on function public.%s from public', f);
    execute format('grant execute on function public.%s to anon, authenticated', f);
  end loop;
end $$;

-- Realtime: ให้ทุกเครื่องเห็นบิล/กะ/การจองทันที (ข้ามตารางที่เปิดอยู่แล้ว)
do $$
declare t text;
begin
  foreach t in array array['lots','lot_groups','items','item_images','sales','expenses','capital_entries','bills','shifts','reservations'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;
